// One-off: turns the old static site's per-page stylesheets into scoped
// stylesheets for the Next.js pages. Every selector is prefixed with the
// page's wrapper class (.pg-<name>), and :root/html/body become the wrapper,
// so pages that reuse class names (.cx, .eyebrow, .ap-*) cannot affect each
// other once loaded side by side. Output: src/styles/pages/<name>.css.
import fs from "node:fs";
import path from "node:path";
import postcss from "postcss";

const L = path.resolve("legacy");
const css = (f) => fs.readFileSync(path.join(L, f), "utf8");
const inline = (f) => [...css(f).matchAll(/<style>([\s\S]*?)<\/style>/g)].map((m) => m[1]).join("\n");
const theme = "public/content/themes/donexa/assets/css/";

const PAGES = {
  home: css(theme + "wef-home.css"),
  mission: inline("pages/mission.html"),
  centers: inline("pages/centers.html"),
  gallery: inline("pages/gallery.html"),
  contact: inline("pages/contact.html"),
  team: inline("team/index.html"),
  donate: inline("donate/index.html"),
  list: inline("pages/active-projects.html"),
  article: inline("build/templates/article.html").replace("{{H1_MAXWIDTH}}", "var(--h1-max, 24ch)"),
  notfound: inline("404.html"),
};

function scopeSelector(sel, scope) {
  const s = sel.trim();
  if (/^(:root|html|body)$/.test(s)) return scope;
  if (/^(html|body)\s+/.test(s)) return s.replace(/^(html|body)\s+/, `${scope} `);
  if (/^(:root|html|body)[.:[]/.test(s)) return scope + s.replace(/^(:root|html|body)/, "");
  return `${scope} ${s}`;
}

const out = path.resolve("src/styles/pages");
fs.mkdirSync(out, { recursive: true });
for (const [name, source] of Object.entries(PAGES)) {
  const scope = `.pg-${name}`;
  const root = postcss.parse(source);
  root.walkRules((rule) => {
    if (rule.parent?.type === "atrule" && /keyframes$/.test(rule.parent.name)) return;
    rule.selectors = rule.selectors.map((s) => scopeSelector(s, scope));
  });
  // @font-face and @import are not expected; drop @import so nothing loads off-site.
  root.walkAtRules("import", (r) => r.remove());
  fs.writeFileSync(
    path.join(out, `${name}.css`),
    `/* GENERATED by scripts/legacy/scope-css.mjs from the old static site. Scoped to ${scope}. */\n` + root.toString().trim() + "\n",
  );
  console.log(name, root.nodes.length);
}
// The fonts are self-hosted by next/font (src/app/layout.tsx) under generated
// family names, exposed as --font-fraunces / --font-jost.
const fonts = (css) => css.replace(/"Fraunces"/g, 'var(--font-fraunces), "Fraunces"').replace(/"Jost"/g, 'var(--font-jost), "Jost"');
for (const f of fs.readdirSync(out)) fs.writeFileSync(path.join(out, f), fonts(fs.readFileSync(path.join(out, f), "utf8")));
for (const f of ["wef-chrome.css", "wef-forms.css", "wef-centers.css", "wef-filters.css"]) {
  fs.writeFileSync(path.resolve("src/styles", f), fonts(fs.readFileSync(path.join(L, theme, f), "utf8")));
}
